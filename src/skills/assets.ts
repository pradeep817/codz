// codz assets: typed names for the images, icons and fonts in the project,
// kept in step with the files. Run it again after adding or removing files.
//
//   Flutter       lib/gen/assets.dart: AppImages.logo = 'assets/images/logo.png' (one class per folder),
//                 and pubspec.yaml lists every asset folder and font family
//   React Native  src/assets/index.ts: images.logo = require('./images/logo.png')
//   Next.js       lib/assets.ts: paths under public/ ('/images/logo.png')
//   React (Vite)  src/assets.ts: public/ paths, and imports for files in src/assets
//   Android, iOS  already typed (R.drawable.logo, Image(.logo)); codz checks resource names
//
// Also lists assets no code uses.

import { join, posix } from 'node:path';
import { loadMap } from '../core/cache.ts';
import { buildChangeSet } from '../core/changeset.ts';
import { loadConfig } from '../core/config.ts';
import { exists, isDir, readText, walk } from '../core/fsutil.ts';
import { ToolError, type Adapter, type ChangeSet, type ProjectMap } from '../core/types.ts';
import { camel, DART_RESERVED, identifier, pascal, TS_RESERVED } from '../input/naming.ts';

const IMAGE = /\.(png|jpe?g|gif|webp|svg|bmp|ico|avif)$/i;
const FONT = /\.(ttf|otf)$/i;
const MEDIA = /\.(png|jpe?g|gif|webp|svg|bmp|ico|avif|json|lottie|riv|mp3|wav|ogg|mp4|webm|ttf|otf|txt|csv|pdf)$/i;
const HEADER = 'Generated by codz assets. Do not edit: add or remove files, then run codz assets again.';

/** Files under a folder, skipping hidden files and Flutter's resolution variants (2.0x/). */
function assetFiles(root: string, dir: string): string[] {
  if (!isDir(join(root, dir))) return [];
  return walk(root, dir, { maxFiles: 5000 })
    .filter((f) => MEDIA.test(f) && !/(^|\/)\./.test(f) && !/\/\d+(\.\d+)?x\//.test(f))
    .sort();
}

/** Unique identifiers for files in one group: logo, logoSvg when two files share a name. */
function names(files: string[], rel: (f: string) => string, reserved: Set<string>): Map<string, string> {
  const base = (f: string) => identifier(posix.basename(f).replace(/\.[^.]+$/, ''), reserved) || 'asset';
  const count = new Map<string, number>();
  for (const f of files) count.set(base(f), (count.get(base(f)) ?? 0) + 1);
  const out = new Map<string, string>();
  const used = new Set<string>();
  for (const f of files) {
    let n = base(f);
    if (count.get(n)! > 1) {
      const sub = posix.dirname(rel(f)).split('/').filter((x) => x && x !== '.').pop();
      n = camel(`${posix.basename(f).replace(/\.[^.]+$/, '')} ${posix.extname(f).slice(1)}`) || n;
      if (used.has(n) && sub) n = camel(`${sub} ${n}`);
    }
    let k = 2;
    const want = n;
    while (used.has(n)) n = `${want}${k++}`;
    used.add(n);
    out.set(f, n);
  }
  return out;
}

/** Assets no source file mentions (by path, file name or generated name). */
function unused(root: string, files: string[], nameOf: Map<string, string>, sources: string[], generatedFile: string): string[] {
  const texts = sources.filter((f) => f !== generatedFile).map((f) => readText(join(root, f)) ?? '').join('\n');
  return files.filter((f) => {
    const n = nameOf.get(f);
    return !texts.includes(posix.basename(f)) && !(n && new RegExp(`\\.${n}\\b`).test(texts));
  });
}

interface Plan {
  files: Map<string, string>;
  summary: string[];
  warnings: string[];
}

// ---------- Flutter ----------

function flutterPubspec(text: string, dirs: string[], fonts: { family: string; files: { asset: string; weight?: number; italic: boolean }[] }[]): string {
  const lines = text.split('\n');
  let start = lines.findIndex((l) => /^flutter:\s*$/.test(l));
  if (start < 0) {
    lines.push('', 'flutter:');
    start = lines.length - 1;
  }
  let end = start + 1;
  while (end < lines.length && (lines[end].trim() === '' || /^\s/.test(lines[end]))) end++;
  // Blank lines after the block stay after it.
  while (end > start + 1 && lines[end - 1].trim() === '') end--;
  const block = lines.slice(start + 1, end);
  const at = (key: string) => block.findIndex((l) => new RegExp(`^  ${key}:\\s*$`).test(l));
  const listEnd = (i: number) => {
    let j = i + 1;
    while (j < block.length && (/^\s{4}/.test(block[j]) || block[j].trim() === '')) j++;
    while (j > i + 1 && block[j - 1].trim() === '') j--;
    return j;
  };
  if (dirs.length) {
    const i = at('assets');
    if (i < 0) block.push('  assets:', ...dirs.map((d) => `    - ${d}/`));
    else {
      const j = listEnd(i);
      const have = block.slice(i + 1, j).map((l) => l.replace(/^\s*-\s*/, '').trim()).filter(Boolean);
      const missing = dirs.map((d) => `${d}/`).filter((d) => !have.includes(d));
      block.splice(j, 0, ...missing.map((d) => `    - ${d}`));
    }
  }
  if (fonts.length) {
    let i = at('fonts');
    if (i < 0) {
      block.push('  fonts:');
      i = block.length - 1;
    }
    const j = listEnd(i);
    const existing = block.slice(i + 1, j).join('\n');
    const add: string[] = [];
    for (const f of fonts) {
      if (new RegExp(`family:\\s*${f.family}\\s*$`, 'm').test(existing)) continue;
      add.push(`    - family: ${f.family}`, '      fonts:', ...f.files.flatMap((x) => [`        - asset: ${x.asset}`, ...(x.weight && x.weight !== 400 ? [`          weight: ${x.weight}`] : []), ...(x.italic ? ['          style: italic'] : [])]));
    }
    block.splice(j, 0, ...add);
  }
  return [...lines.slice(0, start + 1), ...block, ...lines.slice(end)].join('\n');
}

const WEIGHTS: Record<string, number> = { thin: 100, extralight: 200, light: 300, regular: 400, medium: 500, semibold: 600, bold: 700, extrabold: 800, black: 900 };

function planFlutter(root: string, map: ProjectMap, p: Plan): void {
  const pub = readText(join(root, 'pubspec.yaml'));
  if (pub === null) throw new ToolError('not_found', 'No pubspec.yaml.');
  const dir = 'assets';
  const all = assetFiles(root, dir);
  if (!all.length) throw new ToolError('no_assets', 'There is no assets/ folder with files yet.', 'Put images in assets/images and fonts in assets/fonts, then run codz assets.');
  const fontFiles = all.filter((f) => FONT.test(f));
  const others = all.filter((f) => !FONT.test(f));
  // Group by the first folder under assets/: assets/images/x.png → AppImages; files directly in assets → AppAssets.
  const groups = new Map<string, string[]>();
  for (const f of others) {
    const parts = f.split('/');
    const g = parts.length > 2 ? parts[1] : '';
    groups.set(g, [...(groups.get(g) ?? []), f]);
  }
  const out = ['// ' + HEADER, '// ignore_for_file: constant_identifier_names', ''];
  const nameOf = new Map<string, string>();
  const usage: string[] = [];
  for (const [g, files] of [...groups].sort()) {
    const cls = g ? `App${pascal(g)}` : 'AppAssets';
    const ns = names(files, (f) => f.split('/').slice(2).join('/'), DART_RESERVED);
    out.push(`abstract final class ${cls} {`, ...files.map((f) => `  static const ${ns.get(f)} = '${f}';`), '}', '');
    for (const [f, n] of ns) nameOf.set(f, n);
    if (!usage.length) usage.push(`${cls}.${ns.get(files[0])}`);
  }
  const families = new Map<string, { asset: string; weight?: number; italic: boolean }[]>();
  for (const f of fontFiles) {
    const base = posix.basename(f).replace(FONT, '');
    const [fam, style = 'Regular'] = base.split('-');
    const s = style.toLowerCase();
    const italic = /italic/.test(s);
    const weight = WEIGHTS[s.replace('italic', '') || 'regular'];
    families.set(fam, [...(families.get(fam) ?? []), { asset: f, weight, italic }]);
  }
  if (families.size) out.push('abstract final class AppFonts {', ...[...families.keys()].sort().map((fam) => `  static const ${identifier(fam, DART_RESERVED)} = '${fam}';`), '}', '');
  const file = 'lib/gen/assets.dart';
  const text = `${out.join('\n').replace(/\n+$/, '')}\n`;
  if (text !== readText(join(root, file))) {
    p.files.set(file, text);
    p.summary.push(`${exists(join(root, file)) ? 'Update' : 'Create'} ${file}: ${[...groups.keys()].map((g) => (g ? `App${pascal(g)}` : 'AppAssets')).join(', ')}${families.size ? ', AppFonts' : ''} (${others.length} file${others.length === 1 ? '' : 's'}${families.size ? `, ${families.size} font famil${families.size === 1 ? 'y' : 'ies'}` : ''})`);
  }
  const dirs = [...new Set(others.map((f) => posix.dirname(f)))].sort();
  const nextPub = flutterPubspec(pub, dirs, [...families].map(([family, files]) => ({ family, files })));
  if (nextPub !== pub) {
    p.files.set('pubspec.yaml', nextPub);
    p.summary.push('Update pubspec.yaml: every asset folder' + (families.size ? ' and font family' : ''));
  }
  if (usage.length || families.size) p.summary.push(`Use them: ${usage.length ? `Image.asset(${usage[0]})` : ''}${usage.length && families.size ? ', ' : ''}${families.size ? `TextStyle(fontFamily: AppFonts.${identifier([...families.keys()].sort()[0], DART_RESERVED)})` : ''}`);
  const idle = unused(root, others, nameOf, walk(root, 'lib', { exts: ['.dart'] }), file);
  if (idle.length) p.warnings.push(`Not used anywhere in lib/ (${idle.length}): ${idle.slice(0, 10).join(', ')}${idle.length > 10 ? ', …' : ''}`);
}

// ---------- React Native ----------

function planRn(root: string, map: ProjectMap, p: Plan): void {
  const src = map.conventions.srcDir || (isDir(join(root, 'src')) ? 'src' : '.');
  const dir = [`${src}/assets`, 'assets'].find((d) => assetFiles(root, d).length);
  if (!dir) throw new ToolError('no_assets', `There is no ${src}/assets or assets/ folder with files yet.`, 'Put images in src/assets/images, then run codz assets.');
  const files = assetFiles(root, dir).filter((f) => !FONT.test(f));
  const file = `${dir}/index.ts`;
  const groups = new Map<string, string[]>();
  for (const f of files) {
    const rel = f.slice(dir.length + 1).split('/');
    const g = rel.length > 1 ? rel[0] : 'assets';
    groups.set(g, [...(groups.get(g) ?? []), f]);
  }
  const q = "'";
  const out = [`// ${HEADER}`, '// require() needs fixed paths, so every file is listed here.', ''];
  const nameOf = new Map<string, string>();
  for (const [g, fs] of [...groups].sort()) {
    const ns = names(fs, (f) => f.slice(dir.length + 1), TS_RESERVED);
    out.push(`export const ${identifier(g, TS_RESERVED)} = {`, ...fs.map((f) => `  ${ns.get(f)}: require(${q}./${f.slice(dir.length + 1)}${q}),`), '} as const;', '');
    for (const [f, n] of ns) nameOf.set(f, n);
  }
  const text = `${out.join('\n').replace(/\n+$/, '')}\n`;
  if (text !== readText(join(root, file))) {
    p.files.set(file, text);
    p.summary.push(`${exists(join(root, file)) ? 'Update' : 'Create'} ${file}: ${[...groups.keys()].join(', ')} (${files.length} file${files.length === 1 ? '' : 's'})`);
  }
  const first = [...groups].sort()[0];
  p.summary.push(`Use them: <Image source={${identifier(first[0], TS_RESERVED)}.${nameOf.get(first[1][0])}} />`);
  const sources = [src, 'app'].flatMap((d) => walk(root, d, { exts: ['.ts', '.tsx', '.js', '.jsx'] }));
  const idle = unused(root, files, nameOf, sources, file);
  if (idle.length) p.warnings.push(`Not used anywhere (${idle.length}): ${idle.slice(0, 10).join(', ')}${idle.length > 10 ? ', …' : ''}`);
}

// ---------- Next.js and Vite ----------

function planWeb(root: string, map: ProjectMap, vite: boolean, p: Plan): void {
  const pub = assetFiles(root, 'public').filter((f) => !/\/(favicon\.ico|robots\.txt|sitemap\.xml|manifest\.json)$/.test(f));
  const srcAssets = vite ? assetFiles(root, 'src/assets') : [];
  if (!pub.length && !srcAssets.length) throw new ToolError('no_assets', `There are no files in public/${vite ? ' or src/assets/' : ''} yet.`);
  const file = vite ? 'src/assets.ts' : exists(join(root, 'src/app')) ? 'src/lib/assets.ts' : 'lib/assets.ts';
  const out = [`// ${HEADER}`, ''];
  const imports: string[] = [];
  const nameOf = new Map<string, string>();
  if (srcAssets.length) {
    const ns = names(srcAssets, (f) => f.slice('src/assets/'.length), TS_RESERVED);
    for (const f of srcAssets) {
      const n = ns.get(f)!;
      imports.push(`import ${n}Url from './${f.slice('src/'.length)}';`);
      nameOf.set(f, n);
    }
    out.splice(2, 0, ...imports, '');
    out.push('/** Files in src/assets: bundled, with hashed names. */', 'export const bundled = {', ...srcAssets.map((f) => `  ${ns.get(f)}: ${ns.get(f)}Url,`), '} as const;', '');
  }
  if (pub.length) {
    const ns = names(pub, (f) => f.slice('public/'.length), TS_RESERVED);
    out.push('/** Files in public/: served at these paths as they are. */', 'export const publicFiles = {', ...pub.map((f) => `  ${ns.get(f)}: '/${f.slice('public/'.length)}',`), '} as const;', '');
    for (const [f, n] of ns) nameOf.set(f, n);
  }
  const text = `${out.join('\n').replace(/\n+$/, '')}\n`;
  if (text !== readText(join(root, file))) {
    p.files.set(file, text);
    p.summary.push(`${exists(join(root, file)) ? 'Update' : 'Create'} ${file}: ${[srcAssets.length ? `bundled (${srcAssets.length})` : '', pub.length ? `publicFiles (${pub.length})` : ''].filter(Boolean).join(', ')}`);
  }
  if (pub.length) p.summary.push(`Use them: <img src={publicFiles.${nameOf.get(pub[0])}} alt="" />`);
  const sources = ['app', 'src', 'components', 'pages', 'lib'].flatMap((d) => walk(root, d, { exts: ['.ts', '.tsx', '.js', '.jsx', '.css', '.scss'] }));
  const idle = unused(root, [...pub, ...srcAssets], nameOf, sources, file);
  if (idle.length) p.warnings.push(`Not used anywhere (${idle.length}): ${idle.slice(0, 10).join(', ')}${idle.length > 10 ? ', …' : ''}`);
}

// ---------- Android and iOS: already typed ----------

function checkAndroid(root: string, map: ProjectMap, p: Plan): void {
  const res = `${map.conventions.appModule || 'app'}/src/main/res`;
  const files = walk(root, res, { maxFiles: 5000 }).filter((f) => /\/(drawable|mipmap|raw|font)[^/]*\//.test(f));
  const bad = files.filter((f) => !/^[a-z][a-z0-9_]*$/.test(posix.basename(f).replace(/\.9\.png$|\.[^.]+$/, '')));
  p.summary.push(`Android already gives every resource a typed name (R.drawable.logo, R.font.inter); ${files.length} resource file${files.length === 1 ? '' : 's'} checked.`);
  if (bad.length) p.warnings.push(`These resource names will break the build (only a-z, 0-9 and _, starting with a letter): ${bad.slice(0, 10).join(', ')}`);
  const kt = walk(root, map.conventions.srcDir || 'app/src/main/java', { exts: ['.kt'] }).map((f) => readText(join(root, f)) ?? '').join('\n');
  const xml = walk(root, res, { exts: ['.xml'] }).map((f) => readText(join(root, f)) ?? '').join('\n') + (readText(join(root, `${map.conventions.appModule || 'app'}/src/main/AndroidManifest.xml`)) ?? '');
  const idle = files.filter((f) => /\/drawable[^/]*\//.test(f)).filter((f) => {
    const n = posix.basename(f).replace(/\.9\.png$|\.[^.]+$/, '');
    return !new RegExp(`R\\.drawable\\.${n}\\b`).test(kt) && !xml.includes(`@drawable/${n}`);
  });
  if (idle.length) p.warnings.push(`Drawables not used anywhere (${idle.length}): ${idle.slice(0, 10).join(', ')}`);
}

function checkIos(p: Plan): void {
  p.summary.push('Xcode already generates typed names for asset catalog images and colors (Image(.logo), Color(.brand)) when "Generate Asset Symbols" is on (the default in new projects). Nothing to do.');
}

export async function planAssets(root: string, adapter: Adapter): Promise<ChangeSet> {
  const { map } = await loadMap(root, adapter, loadConfig(root).conventions);
  const p: Plan = { files: new Map(), summary: [], warnings: [] };
  if (adapter.id === 'flutter') planFlutter(root, map, p);
  else if (adapter.id === 'react-native') planRn(root, map, p);
  else if (adapter.id === 'nextjs') planWeb(root, map, false, p);
  else if (adapter.id === 'react') planWeb(root, map, true, p);
  else if (adapter.id === 'android') checkAndroid(root, map, p);
  else if (adapter.id === 'ios') checkIos(p);
  else throw new ToolError('not_supported', `codz assets needs a framework adapter; this project uses the ${adapter.id} adapter.`);
  if (!p.files.size && (adapter.id === 'flutter' || adapter.id === 'react-native' || adapter.id === 'nextjs' || adapter.id === 'react')) p.summary.unshift('Asset names are up to date.');
  return buildChangeSet(root, 'assets', { files: p.files, summary: p.summary, warnings: p.warnings, generated: [] });
}
