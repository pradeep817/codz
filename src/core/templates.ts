export function templatesFolder(root: string): string {
  return loadConfig(root).conventions.templatesFolder || DEFAULT_TEMPLATES_FOLDER;
}

const cache = new Map<string, string | null>();

/** The project's template for `id`, or null when it has none. */
export function loadTemplate(root: string, id: string): string | null {
  const file = join(root, templatesFolder(root), `${id}.tmpl`);
  if (!cache.has(file)) cache.set(file, readText(file));
  return cache.get(file)!;
}

/** For tests: forget templates read earlier. */
export function clearTemplateCache(): void {
  cache.clear();
}

/** Fills {{name}} placeholders; unknown ones are left as written and reported. */
export function render(template: string, vars: Record<string, string>): { text: string; unknown: string[] } {
  const unknown: string[] = [];
  const text = template.replace(/\{\{\s*(\w+)\s*\}\}/g, (all, k: string) => {
    if (k in vars) return vars[k];
    unknown.push(k);
    return all;
  });
  return { text, unknown };
}

/**
 * Runs `rendered` (codz's own output) through the project's template, if any.
 * Trailing newlines follow codz's output so blocks still join cleanly.
 */
export function applyTemplate(root: string, id: string, rendered: string, vars: Record<string, string>, warnings?: string[]): string {
  const t = loadTemplate(root, id);
  if (t === null) return rendered;
  const r = render(t, { ...vars, default: rendered });
  if (r.unknown.length && warnings) warnings.push(`Template ${id}.tmpl uses unknown placeholders: ${[...new Set(r.unknown)].map((u) => `{{${u}}}`).join(', ')}. Known: ${Object.keys(TEMPLATES.find((x) => x.id === id)?.vars ?? {}).map((v) => `{{${v}}}`).join(', ')}.`);
  return r.text.replace(/\n+$/, '') + (rendered.match(/\n+$/)?.[0] ?? '');
}

/** The header template for a new file, by extension. */
export function fileHeader(root: string, path: string): string {
  const id = /\.(tsx?|jsx?|mjs)$/.test(path) ? 'file-header.ts' : /\.dart$/.test(path) ? 'file-header.dart' : null;
  if (!id) return '';
  const t = loadTemplate(root, id);
  if (t === null) return '';
  const text = render(t, { file: path }).text;
  return text.endsWith('\n') ? text : `${text}\n`;
}
